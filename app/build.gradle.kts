// Release signing comes from an ignored keystore.properties (storeFile, storePassword, keyAlias,
// keyPassword) at the repository root. Nothing secret is committed; without it, release stays unsigned.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.isFile) file.inputStream().use { load(it) }
}

android {
    namespace = "in.thomas.pocketledger"
    compileSdk = 37
    buildToolsVersion = "37.0.0"
    defaultConfig {
        applicationId = providers.gradleProperty("ledger.testApplicationId").orElse("in.thomas.pocketledger").get()
        minSdk = 28
        targetSdk = 37
        versionCode = 8
        versionName = "1.7.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }
    signingConfigs {
        if (keystoreProperties.getProperty("storeFile") != null) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }
    buildTypes {
        getByName("release") {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
        create("benchmark") {
            initWith(getByName("release"))
            signingConfig = signingConfigs.getByName("debug")
            isMinifyEnabled = false
            isShrinkResources = false
            matchingFallbacks += listOf("release")
        }
    }
    // LedgerFrameTracker (androidx.metrics) exists only in debug and benchmark; release has a no-op stub in src/release.
    sourceSets {
        getByName("debug").kotlin.directories.add("src/tracking/java")
        getByName("benchmark").kotlin.directories.add("src/tracking/java")
        // Exported Room schemas feed MigrationTestHelper in androidTest.
        getByName("androidTest").assets.srcDir("$projectDir/schemas")
    }
    buildFeatures { compose = true }
    compileOptions { sourceCompatibility = JavaVersion.VERSION_17; targetCompatibility = JavaVersion.VERSION_17 }
    // The baseline (app/lint-baseline.xml) is generated by running lint once; see docs/development.md.
    lint {
        baseline = file("lint-baseline.xml")
        abortOnError = true
        checkDependencies = false
        warningsAsErrors = false
        checkReleaseBuilds = true
        htmlReport = true
        xmlReport = true
        textReport = false
    }
}
